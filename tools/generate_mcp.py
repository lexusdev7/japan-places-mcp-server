#!/usr/bin/env python3
"""Generate src/index.js + SYNC.json for the Japan Places MCP server.

Inputs (vendored under tools/inputs/, do not edit by hand):
  - openapi.json       LIVE OpenAPI spec of the Japan Places API
  - mcp-tools.json     canon tool definitions from the site's hosted MCP
  - SPEC_SOURCE.json   provenance of the vendored spec snapshot

Outputs:
  - src/index.js       generated MCP server (zero-dependency, stdio)
  - SYNC.json          sync record {spec_source, catalog_hash, generated_at,
                       tool_count, package_version, paths_covered, tools}

Deterministic: re-running on unchanged inputs produces byte-identical
outputs (generated_at comes from SPEC_SOURCE.json, never the wall clock).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUTS = ROOT / "tools" / "inputs"

TOOL_PATHS = [
    ("jp_municipality", "/poi/municipality"),
    ("jp_quality", "/poi/quality"),
    ("jp_catchment", "/poi/catchment"),
    ("jp_chains", "/poi/chains"),
    ("jp_aliveness", "/poi/aliveness"),
    ("jp_density", "/poi/density"),
    ("jp_energy_price", "/signals/energy/price"),
    ("jp_land_price", "/poi/land/price"),
    ("jp_subsidy_award_rate", "/signals/subsidy/award-rate"),
    ("jp_grant_deadline_alert", "/signals/grant/deadline"),
    ("jp_gbizinfo_search", "/signals/gbizinfo"),
    ("jp_jma_weather", "/signals/jma/weather"),
    ("jp_boj_statistics", "/signals/boj/statistics"),
    ("jp_tourism_signal", "/signals/tourism"),
    ("jp_crime_statistics", "/signals/crime"),
    ("jp_facility_signal", "/signals/facility"),
]

EXTRA_DESCRIPTIONS = {}

# JP-16 canon ruling (2026-11-09, per audit 1.5): the npm tool set IS the
# hosted canon set (functions/mcp-tools.json, 16 tools) - no extra tools.
# The 2.0.0 package added jp_health / jp_catalog / jp_history_diff on top
# of the canon; those three are REMOVED here:
#   - jp_health / jp_catalog duplicate free discovery endpoints (/health,
#     /poi) that are not MCP tools on the hosted server;
#   - jp_history_diff (/diff/{dataset}) stays reachable over REST and the
#     hosted MCP may add it later; until the canon carries it, the npm
#     package does not advertise it.
# check_drift.py watches the live REST spec vs SYNC.json (paths + catalog
# hash), so a future canon change still surfaces as drift.
REMOVED_IN_2_1 = ["jp_health", "jp_catalog", "jp_history_diff"]

PAID_SUFFIX = (
    " [Paid: US${price:.2f} per call via x402 (USDC on Base) or a RapidAPI "
    "Premium Datasets plan (PRO/ULTRA/MEGA). Without payment the API returns "
    "HTTP 402 Payment Required; this server holds no payment credentials and "
    "surfaces the 402 as a clean error.]"
)
PAID_SUFFIX_NOPRICE = (
    " [Paid: gated by HTTP 402 (x402) or a RapidAPI Premium Datasets plan; "
    "the per-call price is stated in the API 402 response. This server holds "
    "no payment credentials and surfaces the 402 as a clean error.]"
)
FREE_SUFFIX = " [Free]"

JS_TEMPLATE = '''#!/usr/bin/env node
/**
 * GENERATED by tools/generate_mcp.py from tools/inputs/openapi.json + tools/inputs/mcp-tools.json - DO NOT EDIT BY HAND. Re-run the generator to update.
 *
 * Japan Places MCP Server
 * Zero-dependency MCP server for the Japan Places API (stdio, JSON-RPC).
 * Publisher: Lexus
 * License: CDLA-Permissive-2.0 AND Apache-2.0
 */

const BASE = process.env.JAPAN_PLACES_BASE || "https://japan-places.local-connect-design.trade";

const SERVER_INFO = { name: "japan-places", version: __VERSION__ };

const TOOLS = __TOOLS__;

const ENDPOINTS = __ENDPOINTS__;

const TOOL_MAP = Object.fromEntries(TOOLS.map((t) => [t.name, t]));

async function callTool(name, args) {
  const tool = TOOL_MAP[name];
  if (!tool) {
    return { isError: true, content: [{ type: "text", text: "unknown tool: " + name }] };
  }
  const ep = ENDPOINTS[name];
  const missing = (tool.inputSchema.required || []).filter(
    (k) => args[k] === undefined || args[k] === null || args[k] === ""
  );
  if (missing.length) {
    return {
      isError: true,
      content: [{ type: "text", text: "Missing required argument(s): " + missing.join(", ") }],
    };
  }
  let path = ep.path;
  const query = {};
  for (const [k, v] of Object.entries(args)) {
    if (v === undefined || v === null || v === "") continue;
    if (ep.pathParams.includes(k)) {
      path = path.replace("{" + k + "}", encodeURIComponent(String(v)));
    } else {
      query[k] = v;
    }
  }
  const url = new URL(BASE + "/api/v1" + path);
  for (const [k, v] of Object.entries(query)) url.searchParams.set(k, String(v));
  const res = await fetch(url, { headers: { accept: "application/json" } });
  const body = await res.text();
  if (res.status === 402) {
    const priceText =
      ep.price !== null && ep.price !== undefined
        ? " - US$" + ep.price.toFixed(2) + " per call via x402 (USDC on Base) or a RapidAPI Premium Datasets plan (PRO/ULTRA/MEGA)."
        : " - gated by x402 / RapidAPI Premium Datasets; the price is stated in the API 402 response.";
    return {
      isError: true,
      content: [
        {
          type: "text",
          text:
            "PAID_DATASET: tool " + name + " (" + ep.path + ") is a paid Japan Places dataset" +
            priceText +
            " The API returned HTTP 402 Payment Required. This MCP server does not hold payment credentials, so it cannot complete the payment. API response: " +
            body.slice(0, 300),
        },
      ],
    };
  }
  if (!res.ok) {
    return {
      isError: true,
      content: [{ type: "text", text: "HTTP " + res.status + " for " + ep.path + ": " + body.slice(0, 300) }],
    };
  }
  let data;
  try {
    data = JSON.parse(body);
  } catch {
    return { content: [{ type: "text", text: body }] };
  }
  return { content: [{ type: "text", text: JSON.stringify(data, null, 2) }] };
}

function reply(id, result) {
  return JSON.stringify({ jsonrpc: "2.0", id, result }) + "\\n";
}

function error(id, code, message) {
  return JSON.stringify({ jsonrpc: "2.0", id, error: { code, message } }) + "\\n";
}

let buf = "";
process.stdin.on("data", async (chunk) => {
  buf += chunk.toString("utf-8");
  let nl;
  while ((nl = buf.indexOf("\\n")) !== -1) {
    const line = buf.slice(0, nl).trim();
    buf = buf.slice(nl + 1);
    if (!line) continue;
    let msg;
    try {
      msg = JSON.parse(line);
    } catch {
      process.stdout.write(error(null, -32700, "parse error"));
      continue;
    }
    const { id, method, params } = msg;
    try {
      if (method === "initialize") {
        process.stdout.write(reply(id, { protocolVersion: "2024-11-05", serverInfo: SERVER_INFO, capabilities: { tools: {} } }));
      } else if (method === "tools/list") {
        process.stdout.write(reply(id, { tools: TOOLS }));
      } else if (method === "tools/call") {
        const result = await callTool(params.name, params.arguments || {});
        process.stdout.write(reply(id, result));
      } else if (method === "ping") {
        process.stdout.write(reply(id, {}));
      } else if (method && method.startsWith("notifications/")) {
      } else {
        process.stdout.write(error(id, -32601, "method not found: " + method));
      }
    } catch (err) {
      process.stdout.write(error(id, -32603, err && err.message ? err.message : String(err)));
    }
  }
});
'''


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def build_input_schema(spec_op, canon_tool):
    """Union of spec parameters and canon properties; spec wins on conflicts."""
    canon_schema = (canon_tool or {}).get("inputSchema", {}) or {}
    canon_props = canon_schema.get("properties", {}) or {}
    params = (spec_op or {}).get("parameters") or []
    properties = {}
    required = []
    for p in params:
        prop = {}
        schema = p.get("schema", {}) or {}
        if "type" in schema:
            prop["type"] = schema["type"]
        if p.get("description"):
            prop["description"] = p["description"]
        if "default" in schema:
            prop["default"] = schema["default"]
        if not prop:
            prop = dict(canon_props.get(p["name"], {"type": "string"}))
        properties[p["name"]] = prop
        if p.get("required"):
            required.append(p["name"])
    for name, prop in canon_props.items():
        if name not in properties:
            properties[name] = prop
    if not params:
        required = list(canon_schema.get("required", []) or [])
    return {"type": "object", "properties": properties, "required": required}


def main():
    spec = load_json(INPUTS / "openapi.json")
    canon = load_json(INPUTS / "mcp-tools.json")
    source = load_json(INPUTS / "SPEC_SOURCE.json")
    package = load_json(ROOT / "package.json")

    canon_by_name = {t["name"]: t for t in canon["tools"]}
    pricing = spec["info"].get("x-pricing", {})
    mcp_prices = pricing.get("x402_per_call", {}).get("mcp", {})
    paid_names = set(mcp_prices)

    tools = []
    endpoints = {}
    for name, path in TOOL_PATHS:
        if path not in spec["paths"]:
            print(f"ERROR: path {path} for tool {name} not in spec", file=sys.stderr)
            return 1
        op = spec["paths"][path].get("get", {})
        canon_tool = canon_by_name.get(name)
        if canon_tool:
            base_desc = canon_tool["description"]
        elif name in EXTRA_DESCRIPTIONS:
            base_desc = EXTRA_DESCRIPTIONS[name]
        else:
            print(f"ERROR: no description source for tool {name}", file=sys.stderr)
            return 1

        price = mcp_prices.get(name)
        paid = name in paid_names
        if paid and price is not None:
            desc = base_desc + PAID_SUFFIX.format(price=price)
        elif paid:
            desc = base_desc + PAID_SUFFIX_NOPRICE
        else:
            desc = base_desc + FREE_SUFFIX

        tools.append({
            "name": name,
            "description": desc,
            "inputSchema": build_input_schema(op, canon_tool),
            # MCP annotation hints (M8ven follow-up, folded into 2.1.0):
            # every tool is a read-only GET against the API - it never
            # mutates state, is safe to retry, and reaches an external
            # service. Directory scorers (M8ven etc.) read these hints.
            "annotations": {
                "readOnlyHint": True,
                "destructiveHint": False,
                "idempotentHint": True,
                "openWorldHint": True,
            },
        })
        path_params = [seg[1:-1] for seg in path.split("/") if seg.startswith("{")]
        endpoints[name] = {
            "path": path,
            "paid": paid,
            "price": price,
            "pathParams": path_params,
        }

    js = (
        JS_TEMPLATE
        .replace("__VERSION__", json.dumps(package["version"]))
        .replace("__TOOLS__", json.dumps(tools, ensure_ascii=False, indent=2))
        .replace("__ENDPOINTS__", json.dumps(endpoints, ensure_ascii=False, indent=2))
    )
    (ROOT / "src" / "index.js").write_text(js, encoding="utf-8")

    sync = {
        "spec_source": source["spec_source"],
        "catalog_hash": spec["info"].get("x-catalog-hash"),
        "generated_at": source["captured_at"],
        "tool_count": len(tools),
        "package_version": package["version"],
        "paths_covered": sorted(spec["paths"].keys()),
        "tools": [t["name"] for t in tools],
    }
    (ROOT / "SYNC.json").write_text(
        json.dumps(sync, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"generated src/index.js + SYNC.json: {len(tools)} tools, "
          f"catalog_hash={sync['catalog_hash']}, paths={len(sync['paths_covered'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
